#!/usr/bin/env python3
"""Inventory of the interface text in keystone-agent, keystone-core, keystone-desktop and keystone-ui.

`python3 scripts/ui-strings.py` rewrites docs/ui-strings.txt from the sources.
`python3 scripts/ui-strings.py --check` fails, printing the difference, when that file is stale,
so every added, changed or removed string shows up in a pull request's diff.

A string literal outside test code counts when it is an argument a label, tooltip, placeholder,
button, menu item, tab, palette item or dialog shows, or when it reads as text anywhere else: a
letter and a space, a capital or a non-ASCII character. Literals inside assertions, logs, key
bindings and selectors never count, and neither do lowercase words, CamelCase key contexts, SQL,
SVG or flags. A lowercase word reached indirectly, such as the relative time "now", is not
caught, and neither is a lowercase word in a bare if or match arm. Each file lists a string once,
so a second "Retry" in the same file does not change the inventory.
"""
import difflib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INVENTORY = ROOT / 'docs/ui-strings.txt'
SOURCES = ['crates/keystone-agent/src', 'crates/keystone-core/src', 'crates/keystone-desktop/src',
           'crates/keystone-ui/src']
SKIP_FILES = {
    'crates/keystone-agent/src/surface.rs',
    'crates/keystone-desktop/src/orchestrator.rs',
    'crates/keystone-ui/src/automation.rs',
    'crates/keystone-ui/src/markdown/mend.rs',
    'crates/keystone-ui/src/theme.rs',
}
SKIP_DIRS = ('crates/keystone-agent/src/bin/', 'crates/keystone-agent/src/mcp/',
             'crates/keystone-ui/src/diagram/')
HEADER = [
    '# Interface text in keystone-agent, keystone-core, keystone-desktop and keystone-ui, by file.',
    '# Generated by scripts/ui-strings.py. Run it after changing interface text and review the diff.',
]
NOT_SHOWN = re.compile(
    r'(?:\w+::)*(?:(?:debug_)?assert\w*!|panic!|unreachable!|todo!|expect|(?:trace|debug|info|warn|error)!'
    r'|e?print(?:ln)?!|var(?:_os)?|include_\w+!|KeyBinding::new|key_context|debug_selector'
    r'|automation_id|id|cfg!)'
)
SHOWN = {
    'Label::new': {0}, 'Tooltip::text': {0}, 'Tooltip::with_key': {0, 1}, 'TextInput::new': {0},
    'MenuHeader::new': {0}, 'Kbd::new': {0}, 'kbd': {0}, 'label': {0}, 'placeholder': {0}, 'tooltip': {0},
    'aria_label': {0}, 'detail': {0}, 'empty_label': {0}, 'confirm_label': {0}, 'child': {0},
    'Button::new': {1}, 'MenuItem::new': {1}, 'Tab::new': {1}, 'PaletteItem::new': {1},
    'CopyButton::new': {1}, 'ConfirmDialog::new': {2, 3}, 'activity_toggle': {1}, 'plural': {1, 2},
}
PASS_THROUGH = {'unwrap_or', 'unwrap_or_else', 'map_or', 'map_or_else', 'Some'}
CONTEXT_CONST = re.compile(r"const \w*CONTEXT\w*\s*:\s*&(?:'static\s+)?str\s*=\s*$")
CONTEXT_NAME = re.compile(r'!?[A-Z][a-z]+(?:[A-Z][a-z]+)+|![A-Z]\w*')
NOT_TEXT = re.compile(r'[a-z]\w*(?:/\w+)+|[A-Z0-9_]+|-{1,2}\w[\w-]*|[a-z]+(?:[A-Z][a-z0-9]*)+|[\w-]+\.[a-z]{1,4}')
SQL = re.compile(r'\s*(?:SELECT|INSERT|UPDATE|DELETE|CREATE|PRAGMA|WITH|BEGIN|ALTER|DROP|COMMIT)\b')


def lex(source):
    """Yield (kind, value, start, end): 'str' literals with their text, 'attr' bodies, and punctuation."""
    i, n = 0, len(source)
    while i < n:
        c = source[i]
        word = re.match(r'(b?)(r)(#*)"', source[i:]) if c in 'br' else None
        if word and not re.match(r'\w', source[i - 1:i]):
            prefix, _, hashes = word.groups()
            begin = i + word.end()
            end = source.index('"' + hashes, begin)
            if not prefix:
                yield ('str', source[begin:end], i, end + 1 + len(hashes))
            i = end + 1 + len(hashes)
        elif source.startswith('//', i):
            i = source.find('\n', i)
            i = n if i < 0 else i
        elif source.startswith('/*', i):
            depth, i = 1, i + 2
            while i < n and depth:
                if source.startswith('/*', i):
                    depth, i = depth + 1, i + 2
                elif source.startswith('*/', i):
                    depth, i = depth - 1, i + 2
                else:
                    i += 1
        elif c == 'b' and source[i + 1:i + 2] in ('"', "'") and not re.match(r'\w', source[i - 1:i]):
            i = skip_quoted(source, i + 1)
        elif c == '"':
            end = skip_quoted(source, i)
            yield ('str', unescape(source[i + 1:end - 1]), i, end)
            i = end
        elif c == "'":
            if source[i + 1:i + 2] == '\\' or source[i + 2:i + 3] == "'":
                i = skip_quoted(source, i)
            else:
                i += 1
        elif source.startswith('#[', i) or source.startswith('#![', i):
            start = i + source[i:].index('[') + 1
            depth, j = 1, start
            while depth:
                if source[j] == '"':
                    j = skip_quoted(source, j)
                    continue
                depth += {'[': 1, ']': -1}.get(source[j], 0)
                j += 1
            yield ('attr', source[start:j - 1], i, j)
            i = j
        elif c in '{}()[];,':
            yield (c, None, i, i + 1)
            i += 1
        else:
            i += 1


def skip_quoted(source, i):
    quote, i = source[i], i + 1
    while source[i] != quote:
        i += 2 if source[i] == '\\' else 1
    return i + 1


def unescape(body):
    body = re.sub(r'\\\n\s*', '', body)
    simple = {'n': '\n', 't': '\t', 'r': '\r', '0': '\0', '\\': '\\', '"': '"', "'": "'"}

    def one(match):
        text = match.group(1)
        if text.startswith('u{'):
            return chr(int(text[2:-1].replace('_', ''), 16))
        if text.startswith('x'):
            return chr(int(text[1:], 16))
        return simple[text]

    return re.sub(r'\\(u\{[0-9a-fA-F_]+\}|x[0-9a-fA-F]{2}|.)', one, body)


def is_test_attr(text):
    text = re.sub(r'\s', '', text)
    if text == 'test':
        return True
    group = r'(?:not|any)\([^()]*(?:\([^()]*\)[^()]*)*\)'
    while re.search(group, text):
        text = re.sub(group, '', text)
    return text.startswith('cfg(') and bool(re.search(r'\btest\b', text))


def strings(source):
    """The interface text of one file's non-test code."""
    found = []
    tokens = list(lex(source))
    stack = []
    k = 0
    while k < len(tokens):
        kind, value, start, end = tokens[k]
        if kind == 'attr' and is_test_attr(value):
            k = skip_item(tokens, k + 1)
            continue
        if kind in '([{':
            callee = re.search(r'([\w:]+!?)\s*$', source[max(0, start - 80):start]) if kind == '(' else None
            stack.append([kind, callee.group(1).removeprefix('::') if callee else '', 0])
        elif kind in ')]}':
            if stack:
                stack.pop()
        elif kind == ',':
            if stack:
                stack[-1][2] += 1
        elif kind == 'str' and not CONTEXT_CONST.search(source[max(0, start - 80):start]) \
                and not re.match(r'\s*\.len\(\)', source[end:end + 12]) and shown(value, calls(stack)):
            found.append(value)
        k += 1
    return found


def skip_item(tokens, k):
    """The index after the item a test-only attribute applies to."""
    depth = 0
    while k < len(tokens):
        kind = tokens[k][0]
        if kind == 'attr':
            pass
        elif kind in '([':
            depth += 1
        elif kind in ')]':
            if depth == 0:
                return k
            depth -= 1
        elif kind == '{' and depth == 0:
            braces = 1
            while braces and k + 1 < len(tokens):
                k += 1
                braces += {'{': 1, '}': -1}.get(tokens[k][0], 0)
            return k + 1
        elif kind in ';,' and depth == 0:
            return k + 1
        elif kind == '}' and depth == 0:
            return k
        k += 1
    return k


def calls(stack):
    """The calls a literal sits in, innermost first, up to the enclosing block."""
    chain = []
    for kind, callee, argument in reversed(stack):
        if kind == '{':
            break
        if kind == '(':
            chain.append((callee, argument))
    return chain


def shown(value, chain):
    if not re.search(r'[^\W\d_]', value):
        return False
    if any(NOT_SHOWN.fullmatch(callee) for callee, _ in chain):
        return False
    direct = next(((callee, argument) for callee, argument in chain if callee not in PASS_THROUGH), None)
    if direct and direct[1] in SHOWN.get('::'.join(direct[0].split('::')[-2:]), ()):
        return True
    if not (re.search(r'\s', value.strip()) or re.search(r'[A-Z]', value) or re.search(r'[^\x00-\x7f]', value)):
        return False
    if NOT_TEXT.fullmatch(value) or CONTEXT_NAME.fullmatch(value.strip()) or SQL.match(value):
        return False
    if value.startswith('<') or re.match(r'\{[A-Z_]+\}\S*$', value):
        return False
    return not re.search(r'&&|\{"|\{\{\\"', value)


def inventory():
    lines = list(HEADER)
    for base in SOURCES:
        for path in sorted((ROOT / base).rglob('*.rs')):
            rel = path.relative_to(ROOT).as_posix()
            if rel in SKIP_FILES or rel.startswith(SKIP_DIRS) or path.name.endswith('_tests.rs'):
                continue
            found = sorted(set(strings(path.read_text(encoding='utf-8'))))
            if found:
                lines.append('')
                lines.append(rel)
                lines.extend('\t' + s.replace('\\', '\\\\').replace('\n', '\\n').replace('\t', '\\t') for s in found)
    return '\n'.join(lines) + '\n'


def main(argv):
    text = inventory()
    if argv[1:] == ['--check']:
        saved = INVENTORY.read_text(encoding='utf-8') if INVENTORY.exists() else ''
        if saved == text:
            return 0
        sys.stdout.writelines(difflib.unified_diff(saved.splitlines(True), text.splitlines(True),
                                                   'docs/ui-strings.txt', 'sources'))
        print('Interface text changed. Run `python3 scripts/ui-strings.py` and commit docs/ui-strings.txt.',
              file=sys.stderr)
        return 1
    if argv[1:]:
        print('Usage: python3 scripts/ui-strings.py [--check]', file=sys.stderr)
        return 2
    INVENTORY.write_text(text, encoding='utf-8')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
