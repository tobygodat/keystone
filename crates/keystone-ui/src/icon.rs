/// Serves every `IconName` as a white-stroked SVG. GPUI tints it with `text_color`.
/// Filled shapes set `fill='white'` on their own paths, since the root sets no fill.
pub struct Icons;

impl AssetSource for Icons {
    fn load(&self, path: &str) -> anyhow::Result<Option<Cow<'static, [u8]>>> {
        let Some(icon) = IconName::ALL.iter().find(|icon| icon.path() == path) else {
            return Ok(None);
        };
        let svg = format!(
            "<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' fill='none' stroke='white' stroke-width='1.5' stroke-linecap='round' stroke-linejoin='round'>{}</svg>",
            icon.shape()
        );
        Ok(Some(Cow::Owned(svg.into_bytes())))
    }

    fn list(&self, path: &str) -> anyhow::Result<Vec<SharedString>> {
        Ok(IconName::ALL
            .iter()
            .map(|icon| icon.path())
            .filter(|key| key.starts_with(path))
            .map(SharedString::from)
            .collect())
    }
}

#[derive(IntoElement)]
pub struct Icon {
    name: IconName,
    color: Color,
    size: Pixels,
}

impl Icon {
    pub fn new(name: IconName) -> Self {
        Self {
            name,
            color: Color::Muted,
            size: px(16.),
        }
    }

    pub fn color(mut self, color: Color) -> Self {
        self.color = color;
        self
    }

    pub fn size(mut self, size: Pixels) -> Self {
        self.size = size;
        self
    }
}

impl RenderOnce for Icon {
    fn render(self, _: &mut Window, cx: &mut App) -> impl IntoElement {
        svg()
            .path(self.name.path())
            .flex_shrink_0()
            .size(self.size)
            .text_color(self.color.to_hsla(cx))
    }
}
